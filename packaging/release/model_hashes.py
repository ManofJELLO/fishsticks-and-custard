#!/usr/bin/env python3
"""Pin the speech-model downloads: write crates/fsc-core/src/model_hashes.rs
with the upstream revisions the app downloads from and the SHA-256 of every
file it may download (the default whisper and VAD models, every whisper.cpp
ggml model, and both files of every voice in voices.rs).

    packaging/release/model_hashes.py            # pin to the newest revisions
    packaging/release/model_hashes.py --keep     # same revisions, re-list files

Pinned URLs can't change under us, and the hashes are checked after each
download. After moving to newer revisions, test speech again (check.py's
models section, the real-model tests) before releasing.
"""

import hashlib
import json
import re
import sys
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "crates/fsc-core/src/model_hashes.rs"
PIPER = "rhasspy/piper-voices"
WHISPER = "ggerganov/whisper.cpp"
SILERO = "snakers4/silero-vad"
SILERO_PATH = "src/silero_vad/data/silero_vad.onnx"


def get(url, timeout=120):
    # Voice names can be non-ASCII ("pt_PT-tugão-medium").
    url = urllib.parse.quote(url, safe=":/?&=%")
    req = urllib.request.Request(url, headers={"User-Agent": "fsc-release-check"})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return r.read()


def hf_head(repo):
    return json.loads(get(f"https://huggingface.co/api/models/{repo}"))["sha"]


def hf_tree(repo, rev, path=""):
    return json.loads(get(f"https://huggingface.co/api/models/{repo}/tree/{rev}/{path}"))


def silero_head():
    commits = json.loads(get(f"https://api.github.com/repos/{SILERO}/commits?path={SILERO_PATH}&per_page=1"))
    return commits[0]["sha"]


def current_pins():
    text = OUT.read_text()
    return {k: re.search(rf'pub const {k}: &str = "([0-9a-f]+)"', text).group(1)
            for k in ("PIPER_REV", "WHISPER_REV", "SILERO_REV")}


def sha_of_url(url):
    return hashlib.sha256(get(url)).hexdigest()


def main():
    if "--keep" in sys.argv:
        pins = current_pins()
    else:
        pins = {"PIPER_REV": hf_head(PIPER), "WHISPER_REV": hf_head(WHISPER), "SILERO_REV": silero_head()}
    hashes = {}

    for entry in hf_tree(WHISPER, pins["WHISPER_REV"]):
        name = entry["path"]
        if re.fullmatch(r"ggml-[\w.-]+\.bin", name) and "lfs" in entry:
            hashes[name] = entry["lfs"]["oid"]

    hashes["silero_vad.onnx"] = sha_of_url(
        f"https://raw.githubusercontent.com/{SILERO}/{pins['SILERO_REV']}/{SILERO_PATH}")

    keys = re.findall(r'key: "([^"]+)"', (ROOT / "crates/fsc-core/src/voices.rs").read_text())
    for i, key in enumerate(keys, 1):
        locale, name, quality = key.split("-", 2)
        folder = f"{locale.split('_')[0]}/{locale}/{name}/{quality}"
        files = {e["path"].rsplit("/", 1)[-1]: e for e in hf_tree(PIPER, pins["PIPER_REV"], folder)}
        model, config = files.get(f"{key}.onnx"), files.get(f"{key}.onnx.json")
        if not model or "lfs" not in model or not config:
            sys.exit(f"{key}: not found at {PIPER}@{pins['PIPER_REV']}")
        hashes[f"{key}.onnx"] = model["lfs"]["oid"]
        # Small files aren't in LFS, so the listing has no SHA-256 for them.
        hashes[f"{key}.onnx.json"] = sha_of_url(
            f"https://huggingface.co/{PIPER}/resolve/{pins['PIPER_REV']}/{folder}/{key}.onnx.json")

    lines = [
        "//! Generated by `packaging/release/model_hashes.py`; don't edit by hand.",
        "//! The upstream revisions speech models are downloaded from, and the",
        "//! SHA-256 of each file this version may download, by file name.",
        "",
        f'pub const PIPER_REV: &str = "{pins["PIPER_REV"]}";',
        f'pub const WHISPER_REV: &str = "{pins["WHISPER_REV"]}";',
        f'pub const SILERO_REV: &str = "{pins["SILERO_REV"]}";',
        "",
        "pub static SHA256: &[(&str, &str)] = &[",
        *[f'    ("{name}", "{sha}"),' for name, sha in sorted(hashes.items())],
        "];",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(hashes)} files", file=sys.stderr)


if __name__ == "__main__":
    main()
